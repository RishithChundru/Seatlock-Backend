-- Gate staff invites. No account exists yet: the invited person creates one from the emailed link (one use,
-- expires) and it joins the organizer as STAFF. Only the SHA-256 of the link's token is stored.
CREATE TABLE staff_invites (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizer_id BIGINT       NOT NULL REFERENCES organizers (id),
    email        VARCHAR(254) NOT NULL,
    name         VARCHAR(60)  NOT NULL,
    token_hash   VARCHAR(64)  NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at      TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT ux_staff_invites_token UNIQUE (token_hash)
);
CREATE INDEX ix_staff_invites_organizer ON staff_invites (organizer_id);
