-- Outside organizers host events on Seatlock. A user applies with a public profile; the super admin
-- (role ADMIN) approves it, and the user becomes an ORGANIZER. Organizers can add gate STAFF.
CREATE TABLE organizers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users (id),
    name          VARCHAR(80)  NOT NULL,
    about         VARCHAR(600) NOT NULL,
    city          VARCHAR(60)  NOT NULL,
    contact_email VARCHAR(120) NOT NULL,
    contact_phone VARCHAR(20)  NOT NULL,
    website       VARCHAR(200),
    status        VARCHAR(20)  NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'SUSPENDED')),
    review_note   VARCHAR(300),
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reviewed_at   TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT ux_organizers_user UNIQUE (user_id)
);
CREATE UNIQUE INDEX ux_organizers_name ON organizers (lower(name));

-- Null organizer = hosted by Seatlock itself (events created by the super admin).
ALTER TABLE events ADD COLUMN organizer_id BIGINT REFERENCES organizers (id);
CREATE INDEX ix_events_organizer ON events (organizer_id);

-- Gate staff belong to one organizer.
ALTER TABLE users ADD COLUMN staff_of BIGINT REFERENCES organizers (id);

ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('USER', 'ADMIN', 'ORGANIZER', 'STAFF'));
