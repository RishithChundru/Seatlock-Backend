-- Baseline: the schema Hibernate created before migrations existed.
-- Databases that already have these tables are *baselined* at V1 (spring.flyway.baseline-on-migrate),
-- so this script only runs on brand-new databases.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    name          VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(255) NOT NULL CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE events (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(255)  NOT NULL,
    venue               VARCHAR(255)  NOT NULL,
    category            VARCHAR(255)  NOT NULL,
    starts_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    price_cents         INTEGER       NOT NULL,
    vip_price_cents     INTEGER,
    premium_price_cents INTEGER,
    description         VARCHAR(1000),
    image_updated_at    TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE event_images (
    event_id     BIGINT      PRIMARY KEY,
    content_type VARCHAR(20) NOT NULL,
    data         BYTEA       NOT NULL
);

CREATE TABLE bookings (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT  NOT NULL REFERENCES users (id),
    event_id         BIGINT  NOT NULL REFERENCES events (id),
    total_cents      INTEGER NOT NULL,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    idempotency_key  VARCHAR(100),
    ticket_code      VARCHAR(20),
    ticket_issued_at TIMESTAMP(6) WITH TIME ZONE,
    status           VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    cancelled_at     TIMESTAMP(6) WITH TIME ZONE,
    checked_in_at    TIMESTAMP(6) WITH TIME ZONE,
    seat_labels      VARCHAR(400),
    CONSTRAINT uk_bookings_user_idempotency UNIQUE (user_id, idempotency_key)
);

CREATE TABLE seats (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT       NOT NULL REFERENCES events (id),
    row_label   VARCHAR(255) NOT NULL,
    seat_number INTEGER      NOT NULL,
    status      VARCHAR(255) NOT NULL CHECK (status IN ('AVAILABLE', 'BOOKED')),
    tier        VARCHAR(10)  NOT NULL DEFAULT 'STANDARD' CHECK (tier IN ('VIP', 'PREMIUM', 'STANDARD')),
    booking_id  BIGINT REFERENCES bookings (id),
    version     BIGINT       NOT NULL,
    CONSTRAINT uk_seats_event_row_number UNIQUE (event_id, row_label, seat_number)
);

CREATE TABLE waitlist_entries (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id           BIGINT NOT NULL REFERENCES events (id),
    user_id            BIGINT NOT NULL REFERENCES users (id),
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    offered_seat_id    BIGINT,
    offered_seat_label VARCHAR(8),
    offer_expires_at   TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_waitlist_event_user UNIQUE (event_id, user_id)
);
