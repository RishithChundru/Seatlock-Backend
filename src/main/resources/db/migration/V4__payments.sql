-- One row per Razorpay order. It remembers which seats the order pays for, so the booking can be made by
-- whichever arrives first: the browser's verify call or Razorpay's webhook.
-- event_id / booking_id are plain ids (no FK) so deleting an event with refunded payments isn't blocked.
CREATE TABLE payments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES users (id),
    event_id            BIGINT NOT NULL,
    seat_ids            VARCHAR(200) NOT NULL,
    amount_cents        INTEGER NOT NULL,
    razorpay_order_id   VARCHAR(40) NOT NULL,
    razorpay_payment_id VARCHAR(40),
    booking_id          BIGINT,
    status              VARCHAR(20) NOT NULL,
    idempotency_key     VARCHAR(100),
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ux_payments_order UNIQUE (razorpay_order_id),
    CONSTRAINT ux_payments_user_idempotency UNIQUE (user_id, idempotency_key)
);
CREATE INDEX ix_payments_booking ON payments (booking_id);
